// Saves Blend Planner output to the shared blend_plans table.
//
// The planner code is only an internal queue reference. The operator assigns
// the real Fort Worth blend number when the plan is promoted in Blend Case
// Manager. Every save inserts a new row; prior plans are never overwritten.

import { supabase } from './supabaseClient';

const TANK_ASSET_TAG = {
  TK55: '23155',
  TK56: '23156',
  TK04: '27404',
  TK05: '27405',
};

function tankAssetTagFor(blend) {
  return TANK_ASSET_TAG[blend.tankId] ?? null;
}

function safeToken(value, fallback = 'NA') {
  const token = String(value || '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '')
    .slice(0, 12);
  return token || fallback;
}

function planCodeFor(blend, index, savedAt) {
  const day = String(blend.startDate || savedAt.slice(0, 10)).replaceAll('-', '');
  const tank = safeToken(blend.tankId || blend.tankLabel, 'TANK');
  const time = savedAt.replace(/\D/g, '').slice(8, 17);
  const random = Math.random().toString(36).slice(2, 6).toUpperCase();
  return `PLAN-${day}-${tank}-${time}-${String(index + 1).padStart(2, '0')}${random}`;
}

function planRow({ terminalConfig, blend, blendTarget, notes, startDate, index, savedAt }) {
  const incomingRvp = Number(blend.rvpActual ?? 0);
  const targetRvp = Number(blendTarget ?? blend.blendTarget ?? blend.blendedRVP ?? 0);
  const plannedButane = Number(blend.butane_bbls ?? 0);
  const plannedTrucks = Number(blend.trucks ?? 0);
  const predictedFinalRvp = Number(blend.blendedRVP ?? 0);

  return {
    plan_code: planCodeFor(blend, index, savedAt),
    label: `Blend ${blend.blendNumber}`,
    status: 'planned',
    grade: String(blend.product || 'REGULAR').toUpperCase(),
    tank: blend.tankLabel || blend.tankId,
    tank_no: tankAssetTagFor(blend),
    window_start: `${blend.startDate} ${blend.startTime}`,
    window_end: `${blend.endDate} ${blend.endTime}`,
    truck_start: blend.truckStart || null,
    truck_finish: blend.truckFinish || null,
    est_pumpable_bbl: Number(blend.estPumpable ?? 0),
    est_tov_bbl: Number(blend.estTOV ?? 0),
    incoming_rvp: incomingRvp,
    target_rvp: targetRvp,
    butane_bbl: plannedButane,
    trucks: plannedTrucks,
    blended_rvp: predictedFinalRvp,
    source_week: startDate,
    assumption: notes?.trim()
      ? notes.trim()
      : `Generated by Blend Planner from ${terminalConfig?.name ?? 'terminal'} inventory and schedule inputs as of ${startDate}.`,
    planner_snapshot: {
      savedAt,
      terminal: terminalConfig?.name ?? null,
      blendNumber: blend.blendNumber ?? null,
      tankId: blend.tankId ?? null,
      tankLabel: blend.tankLabel ?? null,
      tankAssetTag: tankAssetTagFor(blend),
      product: blend.product ?? null,
      startDate: blend.startDate ?? null,
      startTime: blend.startTime ?? null,
      endDate: blend.endDate ?? null,
      endTime: blend.endTime ?? null,
      truckStart: blend.truckStart ?? null,
      truckFinish: blend.truckFinish ?? null,
      estimatedPumpableBbl: Number(blend.estPumpable ?? 0),
      estimatedTovBbl: Number(blend.estTOV ?? 0),
      incomingRvp,
      targetRvp,
      plannedButaneBbl: plannedButane,
      plannedTruckCount: plannedTrucks,
      predictedFinalRvp,
    },
  };
}

export async function savePlanToSupabase({ terminalConfig, blends, startDate, blendTarget, notes }) {
  if (!Array.isArray(blends) || blends.length === 0) {
    return { success: false, error: 'No blends to save' };
  }

  const savedAt = new Date().toISOString();
  const rows = blends.map((blend, index) => planRow({
    terminalConfig,
    blend,
    blendTarget,
    notes,
    startDate,
    index,
    savedAt,
  }));

  const { data, error } = await supabase.rpc('insert_blend_plans_bulk', { p_rows: rows });
  if (error) {
    console.error('[savePlanToSupabase] insert failed:', error);
    return { success: false, error: error.message || 'Unknown Supabase error' };
  }

  return { success: true, rowsAdded: data?.length ?? rows.length, rowsUpdated: 0 };
}
